#!/usr/bin/env node
// build-redirects.mjs: compile migration/redirects/*.tsv into the retired docs
// hosts' redirect Worker (redirects/worker.js).
//
// Each TSV is named <old-host>--<segment>.tsv and holds "<old path>\t<new path>"
// lines, one per URL of the old site's sitemap. The Worker answers every request
// to a retired host with a 301 to the mapped page on docs.vulnetix.com, or to the
// host's fallback segment when the path is not in the map (a deep link the old
// sitemap never listed). An alias host (scripts/lib/redirects.mjs ALIASES) is
// answered from another host's map. The reading rules live in
// scripts/lib/redirects.mjs.
//
// Usage: node scripts/build-redirects.mjs [--check dist]
//   --check dist  also fail unless every target exists in the built site.

import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, FALLBACK, ALIASES, isAbsolute, loadRedirects } from './lib/redirects.mjs';

const OUT = join(ROOT, 'redirects/worker.js');
const SITE = 'https://docs.vulnetix.com';

const map = loadRedirects();

const check = process.argv.indexOf('--check');
if (check > 0) {
  const dist = process.argv[check + 1] ?? 'dist';
  const missing = [];
  for (const [host, paths] of Object.entries(map)) {
    for (const [from, to] of Object.entries(paths)) {
      if (isAbsolute(to)) continue;
      const p = to.split('#')[0].replace(/^\/|\/$/g, '');
      if (!existsSync(join(ROOT, dist, p, 'index.html'))) missing.push(`${host}${from} -> ${to}`);
    }
  }
  for (const [host, to] of Object.entries(FALLBACK)) {
    if (!existsSync(join(ROOT, dist, to.replace(/^\/|\/$/g, ''), 'index.html'))) missing.push(`${host} fallback -> ${to}`);
  }
  if (missing.length) {
    console.error(`${missing.length} redirect target(s) missing from ${dist}:\n${missing.join('\n')}`);
    process.exit(1);
  }
}

const worker = `// Generated by scripts/build-redirects.mjs from migration/redirects/*.tsv.
// Do not edit: change a TSV and rebuild.
//
// Retired Vulnetix docs hosts: every request gets a 301 to its page on
// ${SITE}, or to the host's product segment when the old path is unknown.
// An alias host is answered from another host's map.
const SITE = ${JSON.stringify(SITE)};
const FALLBACK = ${JSON.stringify(FALLBACK)};
const ALIASES = ${JSON.stringify(ALIASES)};
const MAP = ${JSON.stringify(map)};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const host = ALIASES[url.hostname] ?? url.hostname;
    const paths = MAP[host];
    if (!paths) return new Response('Not a retired docs host', { status: 404 });
    let p = url.pathname;
    if (!p.endsWith('/') && !/\\.[a-z0-9]+$/i.test(p)) p += '/';
    const target = paths[p] ?? paths[p.replace(/index\\.html$/, '')] ?? FALLBACK[host];
    const [path, frag] = target.split('#');
    const dest = (/^https?:\\/\\//.test(path) ? path : SITE + path + url.search) + (frag ? '#' + frag : '');
    return new Response(null, { status: 301, headers: { location: dest, 'cache-control': 'public, max-age=86400' } });
  },
};
`;
writeFileSync(OUT, worker);
const total = Object.values(map).reduce((n, m) => n + Object.keys(m).length, 0);
console.log(`redirects/worker.js: ${total} paths across ${Object.keys(map).length} hosts, plus ${Object.keys(ALIASES).length} alias host(s)`);
