#!/usr/bin/env node
// build-redirects.mjs: compile migration/redirects/*.tsv into the retired docs
// hosts' redirect Worker (redirects/worker.js).
//
// Each TSV is named <old-host>--<segment>.tsv and holds "<old path>\t<new path>"
// lines, one per URL of the old site's sitemap. The Worker answers every request
// to a retired host with a 301 to the mapped page on docs.vulnetix.com, or to the
// host's fallback segment when the path is not in the map (a deep link the old
// sitemap never listed).
//
// A segment's home page is served at /<segment>/, not at its file path, so a
// target naming the home page by path is rewritten to the segment root here.
//
// Usage: node scripts/build-redirects.mjs [--check dist]
//   --check dist  also fail unless every target exists in the built site.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const MAPS = join(ROOT, 'migration/redirects');
const SEGMENTS = join(ROOT, 'src/segments');
const OUT = join(ROOT, 'redirects/worker.js');
const SITE = 'https://docs.vulnetix.com';

// Where an unmapped path on each retired host goes.
const FALLBACK = {
  'docs.cli.vulnetix.com': '/cli/',
  'docs.guardrails.vulnetix.com': '/ai-firewall/',
  'docs.mcp.vulnetix.com': '/mcp-server/',
  'ai-docs.vulnetix.com': '/pix/',
  'docs.code.vulnetix.com': '/vscode/',
};

const homes = new Map([['software-factory/get-started/overview', 'software-factory']]);
for (const f of readdirSync(SEGMENTS).filter((f) => f.endsWith('.json'))) {
  const s = JSON.parse(readFileSync(join(SEGMENTS, f), 'utf8'));
  homes.set(s.home, s.id);
}

const canon = (target) => {
  const [path, frag] = target.split('#');
  const id = path.replace(/^\/|\/$/g, '');
  const p = homes.has(id) ? `/${homes.get(id)}/` : `/${id}/`;
  return frag ? `${p}#${frag}` : p;
};
const key = (path) => {
  let p = path.split('?')[0].split('#')[0];
  if (!p.startsWith('/')) p = `/${p}`;
  if (!p.endsWith('/') && !/\.[a-z0-9]+$/i.test(p)) p += '/';
  return p;
};

const map = {};
for (const f of readdirSync(MAPS).filter((f) => f.endsWith('.tsv')).sort()) {
  const host = basename(f).split('--')[0];
  if (!FALLBACK[host]) throw new Error(`${f}: no fallback for host ${host}`);
  map[host] ??= {};
  for (const [i, line] of readFileSync(join(MAPS, f), 'utf8').split('\n').entries()) {
    if (!line.trim()) continue;
    const [from, to, extra] = line.split('\t');
    if (!from || !to || extra !== undefined) throw new Error(`${f}:${i + 1}: want "<old>\\t<new>"`);
    const k = key(from);
    const v = canon(to);
    if (map[host][k] && map[host][k] !== v) throw new Error(`${f}:${i + 1}: ${host}${k} maps to both ${map[host][k]} and ${v}`);
    map[host][k] = v;
  }
}

const check = process.argv.indexOf('--check');
if (check > 0) {
  const dist = process.argv[check + 1] ?? 'dist';
  const missing = [];
  for (const [host, paths] of Object.entries(map)) {
    for (const [from, to] of Object.entries(paths)) {
      const p = to.split('#')[0].replace(/^\/|\/$/g, '');
      if (!existsSync(join(ROOT, dist, p, 'index.html'))) missing.push(`${host}${from} -> ${to}`);
    }
  }
  for (const [host, to] of Object.entries(FALLBACK)) {
    if (!existsSync(join(ROOT, dist, to.replace(/^\/|\/$/g, ''), 'index.html'))) missing.push(`${host} fallback -> ${to}`);
  }
  if (missing.length) {
    console.error(`${missing.length} redirect target(s) missing from ${dist}:\n${missing.join('\n')}`);
    process.exit(1);
  }
}

const worker = `// Generated by scripts/build-redirects.mjs from migration/redirects/*.tsv.
// Do not edit: change a TSV and rebuild.
//
// Retired Vulnetix docs hosts: every request gets a 301 to its page on
// ${SITE}, or to the host's product segment when the old path is unknown.
const SITE = ${JSON.stringify(SITE)};
const FALLBACK = ${JSON.stringify(FALLBACK)};
const MAP = ${JSON.stringify(map)};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const paths = MAP[url.hostname];
    if (!paths) return new Response('Not a retired docs host', { status: 404 });
    let p = url.pathname;
    if (!p.endsWith('/') && !/\\.[a-z0-9]+$/i.test(p)) p += '/';
    const target = paths[p] ?? paths[p.replace(/index\\.html$/, '')] ?? FALLBACK[url.hostname];
    const [path, frag] = target.split('#');
    const dest = SITE + path + url.search + (frag ? '#' + frag : '');
    return new Response(null, { status: 301, headers: { location: dest, 'cache-control': 'public, max-age=86400' } });
  },
};
`;
writeFileSync(OUT, worker);
const total = Object.values(map).reduce((n, m) => n + Object.keys(m).length, 0);
console.log(`redirects/worker.js: ${total} paths across ${Object.keys(map).length} hosts`);
