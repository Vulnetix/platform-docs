#!/usr/bin/env node
// gha-scanners.mjs: write the third-party scanner catalogue page for
// `vulnetix gha setup` from the Vulnetix CLI repository.
//
// Where it comes from:
//   The catalogue is internal/ghasetup/catalog (embedded in the CLI). The CLI
//   renders website/content/docs/ci-cd/third-party-scanners.md from it with
//   internal/ghasetup/ghasetupgen (`just gen-gha-setup`), using the same
//   Render() that `vulnetix gha setup` writes into a repository, so every job
//   on the page is the job the command produces.
//
//   This script reads that rendered Hugo page from a git ref of the cli
//   repository (default origin/main) and converts it: Hugo callout shortcodes
//   become plain blockquotes, `{#id}` heading suffixes are dropped and the
//   in-page links are rewritten to the ids Astro assigns, and em dashes in
//   prose and comments become commas.
//
// Output, in this repository:
//   src/content/docs/cli/ci-cd/third-party-scanners.md   (generated: true)
//
// Usage:
//   node migration/generators/gha-scanners.mjs [--cli <path>] [--ref <git ref>] [--out <dir>]
//
// No dependencies beyond Node 20.

import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

const here = dirname(new URL(import.meta.url).pathname);
const root = resolve(here, '..', '..');
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const cli = resolve(opt('cli', process.env.VULNETIX_CLI_REPO || resolve(root, '..', 'cli')));
const ref = opt('ref', 'origin/main');
const outRoot = resolve(opt('out', join(root, 'src', 'content', 'docs')));
const srcPath = 'website/content/docs/ci-cd/third-party-scanners.md';

if (!existsSync(join(cli, '.git'))) {
  console.error(`gha-scanners: ${cli} is not a git checkout; pass --cli <path to the cli repository>`);
  process.exit(2);
}
const git = (...a) => execFileSync('git', ['-C', cli, ...a], { encoding: 'utf8', maxBuffer: 64 << 20 });

const sha = git('rev-parse', '--short=9', ref).trim();
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const updated = (() => {
  const d = new Date(`${git('log', '-1', '--format=%cs', ref).trim()}T00:00:00Z`);
  return `${String(d.getUTCDate()).padStart(2, '0')} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
})();

const src = git('show', `${ref}:${srcPath}`);
const fmEnd = src.indexOf('\n---\n', 4);
let body = src.slice(fmEnd + 5);

// Drop the generator's own Hugo notice; the frontmatter and banner replace it.
body = body.replace(/^\{\{< callout type="info" >\}\}\nThis page is generated[\s\S]*?\{\{< \/callout >\}\}\n\n/m, '');

// Remaining callouts are warnings about a specific scanner: a plain blockquote.
body = body.replace(/\{\{< callout type="[a-z]+" >\}\}\n([\s\S]*?)\n\{\{< \/callout >\}\}/g, (_, inner) =>
  inner.split('\n').map((l) => (l ? `> ${l}` : '>')).join('\n'));

// Heading ids: Astro assigns github-slugger ids, so drop the Hugo `{#id}` and
// point the table links at the id the heading will get.
const slugger = new Map();
const slugify = (text) => {
  let s = text.toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
  const n = slugger.get(s) ?? 0;
  slugger.set(s, n + 1);
  return n ? `${s}-${n}` : s;
};
const idMap = new Map();
let inFence = false;
body = body.split('\n').map((line) => {
  if (/^```/.test(line)) inFence = !inFence;
  if (inFence) return line;
  const h = line.match(/^(#{1,6}) (.*?)(?: \{#([a-z0-9-]+)\})?$/);
  if (!h) return line;
  const id = slugify(h[2].replace(/`/g, ''));
  if (h[3]) idMap.set(h[3], id);
  return `${h[1]} ${h[2]}`;
}).join('\n');
body = body.replace(/\]\(#([a-z0-9-]+)\)/g, (m, id) => (idMap.has(id) ? `](#${idMap.get(id)})` : m));

// Docs rule: no em dashes.
body = body.replace(/\s+\u2014\s+/g, ', ').replace(/\u2014/g, ', ');

// Old-site links.
body = body.replace(/\]\(\{\{< relref "gha-command" >\}\}\)/g, '](/cli/ci-cd/gha-command/)');
if (/\{\{</.test(body)) {
  console.error('gha-scanners: an unconverted Hugo shortcode is left in the page');
  process.exit(1);
}

const fm = [
  '---',
  'title: "Third-party scanners"',
  'description: "Every scanner vulnetix gha setup can add to a GitHub Actions workflow, the exact job it writes, and how the publish job sends each report to Vulnetix under the tool that produced it."',
  'order: 3',
  'sources: ["cli/internal/ghasetup/catalog", "cli/internal/ghasetup/render.go", "cli/internal/ghasetup/ghasetupgen/main.go"]',
  `checked: ["cli@${sha}"]`,
  `updated: "${updated}"`,
  'generated: true',
  '---',
  '',
  `<!-- Generated by migration/generators/gha-scanners.mjs from cli/${srcPath} at cli@${sha}. Edit internal/ghasetup/catalog, not this page. -->`,
  '',
  '',
].join('\n');

const out = join(outRoot, 'cli', 'ci-cd', 'third-party-scanners.md');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, fm + body.replace(/^\n+/, ''));
console.log(`gha-scanners: wrote ${out} (cli@${sha}, ${idMap.size} scanner anchors)`);
