import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mdHref, toMarkdown, transformBody } from '../src/lib/markdown-export.mjs';
import { SEED, fc } from './property.mjs';

test('mdHref puts .md in place of the trailing slash', () => {
  assert.equal(mdHref('/'), '/index.md');
  assert.equal(mdHref('/cli/'), '/cli.md');
  assert.equal(mdHref('/cli/get-started/install/'), '/cli/get-started/install.md');
});

test('page links point at the Markdown twin, keeping the anchor', () => {
  assert.equal(transformBody('See [install](/cli/get-started/install/#homebrew).'), 'See [install](/cli/get-started/install.md#homebrew).');
  assert.equal(transformBody('[CLI](/cli/) and [home](/)'), '[CLI](/cli.md) and [home](/index.md)');
  assert.equal(transformBody('[overview](/cli/get-started/overview/)'), '[overview](/cli.md)');
  assert.equal(transformBody('[k]: /cli/get-started/install/'), '[k]: /cli/get-started/install.md');
  assert.equal(transformBody('[`vulnetix config plan`](/platform-iac/cli/plan/)'), '[`vulnetix config plan`](/platform-iac/cli/plan.md)');
});

test('assets, external links and code are left alone', () => {
  assert.equal(transformBody('![x](/img/sf-events-dark.webp)'), '![x](/img/sf-events-dark.webp)');
  assert.equal(transformBody('[s](/?search)'), '[s](/?search)');
  assert.equal(transformBody('[gh](https://github.com/)'), '[gh](https://github.com/)');
  assert.equal(transformBody('`[i](/cli/get-started/install/)`'), '`[i](/cli/get-started/install/)`');
  const fenced = '```md\n[i](/cli/get-started/install/)\n<!-- kept -->\n```';
  assert.equal(transformBody(fenced), fenced);
});

test('links to pages not written yet become their text', () => {
  assert.equal(transformBody('[soon](/cli/nope/not-a-page/)'), 'soon');
});

test('comments and extra blank lines are dropped', () => {
  assert.equal(transformBody('<!-- Generated by x -->\n\n\n\nBody  \n'), 'Body');
});

test('the twin is title, description, status when not available, then body', () => {
  assert.equal(toMarkdown({ title: 'T', description: 'D.', status: 'available', body: 'B' }), '# T\n\nD.\n\nB\n');
  assert.match(toMarkdown({ title: 'T', description: 'D.', status: 'planned', body: 'B' }), /^# T\n\nD\.\n\nStatus: planned\. .*\n\nB\n$/);
});

test('NUL bytes in the input cannot fake a span marker', () => {
  assert.equal(transformBody('tail \x003\x00 end'), 'tail \x003\x00 end');
  assert.equal(transformBody('`code` \x000\x00 end'), '`code` \x000\x00 end');
});

test('transformBody never panics on arbitrary strings', () => {
  fc.assert(fc.property(fc.string(), (s) => { transformBody(s); return true; }), { seed: SEED });
});

test('toMarkdown never panics on arbitrary strings', () => {
  fc.assert(fc.property(fc.string(), (s) => { toMarkdown({ title: s, description: s, status: s, body: s }); return true; }), { seed: SEED });
});

test('transformBody is idempotent', () => {
  fc.assert(fc.property(fc.string(), (s) => assert.equal(transformBody(transformBody(s)), transformBody(s))), { seed: SEED });
});
